/**
 * Слой временных данных.
 *
 * Экраны из `design/STITCH-SCREENS.md` опережают бекенд: смен, расходов,
 * поставщиков, списаний и уведомлений там пока нет (полный список —
 * `design/BACKEND-REQUESTS.md`). Чтобы экраны можно было делать и
 * показывать уже сейчас, недостающие ответы отдаёт этот слой.
 *
 * Правила, чтобы моки не превратились во вторую реализацию:
 *
 * 1. Мок живёт **только** внутри `lib/api/*`. Компонент не знает, откуда
 *    пришли данные, и при появлении эндпоинта не меняется вообще.
 * 2. Каждая заглушка помечена комментарием `// MOCK: <МЕТОД> <путь>` —
 *    ровно тем путём, который описан в `BACKEND-REQUESTS.md`. Поиск по
 *    строке `MOCK:` даёт полный список того, что осталось подключить.
 * 3. Заглушка отвечает с задержкой: без неё скелеты загрузки никогда не
 *    показываются, и на реальной сети экран впервые видят пользователи.
 */

const DELAY_MS = 320;

export function mock<T>(value: T): Promise<T> {
  return new Promise((resolve) => {
    setTimeout(() => resolve(value), DELAY_MS);
  });
}

/** Признак того, что экран работает на заглушке — для плашки в интерфейсе. */
export const IS_MOCK = true;
